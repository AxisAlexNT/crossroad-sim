import assert from 'node:assert/strict';
import { InteractiveRuntime, type InteractiveFrame } from '../src/engine/interactiveRuntime';
import { defaultModel } from '../src/engine/presets';
import { compileModel } from '../src/engine/compile';
import { Simulation } from '../src/engine/sim';

const cfg = defaultModel('v1');
const direct = new Simulation(cfg, compileModel(cfg).code);
const runtime = new InteractiveRuntime();
let frame = structuredClone(runtime.execute({ type: 'init', cfg })!);
assert.deepEqual(frame.state, direct.st);
let quanta = 0;
do {
  frame = structuredClone(runtime.execute({ type: 'advance', target: 120 }, true, .5)!);
  quanta++;
} while (!frame.complete);
assert.ok(quanta > 1, 'Длинный расчёт должен делиться на кванты');
direct.runUntil(120);
assert.deepEqual(frame.state, direct.st);
assert.deepEqual(frame.details?.series, direct.series);
assert.deepEqual(frame.details?.log, direct.log);
assert.deepEqual(frame.permit, direct.permit);
assert.deepEqual(frame.pedSignals, direct.net.pedEdges.map((_, i) => direct.pedSignal(i)));
const saved: InteractiveFrame = structuredClone(frame);
assert.throws(() => runtime.execute({ type: 'advance', target: Infinity }));
assert.deepEqual(runtime.execute({ type: 'snapshot' })!.state, saved.state);
direct.runToNextLampChange();
do { frame = structuredClone(runtime.execute({ type: 'nextPhase' }, true, .5)!); } while (!frame.complete);
assert.deepEqual(frame.state, direct.st);
assert.equal(runtime.execute({ type: 'back', seconds: 10 })!.complete, direct.back(10));
assert.deepEqual(runtime.execute({ type: 'snapshot' }, true)!.state, direct.st);
assert.deepEqual(runtime.execute({ type: 'snapshot' }, true)!.details?.series, direct.series);
assert.equal(runtime.execute({ type: 'previousPhase' })!.complete, direct.backToPrevLampChange());
assert.deepEqual(runtime.execute({ type: 'snapshot' })!.state, direct.st);
assert.equal(runtime.execute({ type: 'dispose' }), null);
assert.throws(() => runtime.execute({ type: 'snapshot' }));
assert.equal(saved.state.t, 120, 'Переданный снимок не меняется вслед за движком');
direct.dispose();
console.log(`Фоновый протокол: ${quanta} квантов, совпадают состояние, сигналы, журнал, ряды и перемотка`);
